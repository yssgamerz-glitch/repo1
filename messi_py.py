SUBJECT_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(student_record):
    """Return the total of a student's numeric scores, skipping the name."""
    total = 0
    for index in range(1, len(student_record)):
        total = total + student_record[index]
    return total


def average_score(total):
    """Return the mean of a student's scores across all subjects."""
    return total / SUBJECT_COUNT


def student_average(student_record):
    """Return one student's subject average."""
    return average_score(sum_scores(student_record))


def class_average(student_records):
    """Return the mean of all students' averages."""
    total_of_averages = 0
    for student in student_records:
        total_of_averages = total_of_averages + student_average(student)
    return total_of_averages / len(student_records)


def count_above_class_average(student_records):
    """Return how many students scored above the class average."""
    mean = class_average(student_records)
    count = 0
    for student in student_records:
        if student_average(student) > mean:
            count = count + 1
    return count


